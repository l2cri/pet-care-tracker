/**
 * Пресеты ухода (SPEC, «Пресеты ухода»; User Story 3).
 *
 * Стартовый набор пунктов ухода нового подопечного: прививки — 12 месяцев,
 * паразиты — 3 месяца, груминг — 2 месяца. Пресет — предложение по умолчанию,
 * а не обязательная программа: пользователь правит и удаляет пункты до
 * сохранения (тикет 04) и позже в карточке питомца (тикет 05).
 *
 * Черновик, а не сущность: без id и subjectId — их выдаёт app-слой при
 * создании (crypto.randomUUID, см. model.ts), поэтому пресеты остаются
 * чистыми данными домена.
 */

import type { Interval } from './model'

/** Черновик пункта ухода: заголовок и интервал; id и subjectId выдаёт app при создании. */
export interface CareItemDraft {
  title: string;
  interval: Interval;
}

/**
 * Пресетный набор ухода для нового подопечного. Каждый вызов возвращает
 * свежие объекты: форма редактирует черновики на месте, и правки не должны
 * протекать в следующие вызовы (новый питомец получает нетронутый набор).
 */
export function presetCareItemDrafts(): CareItemDraft[] {
  return [
    { title: 'Прививка', interval: { value: 12, unit: 'months' } },
    { title: 'Обработка от паразитов', interval: { value: 3, unit: 'months' } },
    { title: 'Груминг', interval: { value: 2, unit: 'months' } },
  ];
}
